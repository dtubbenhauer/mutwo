#!/usr/bin/env python3
"""Generate finite affine-window certificates; Lean rechecks every claim.

This generator has no mathematical trust role. It uses only the definition
in main.tex §1C, not the proposed mu values or KL engine. Run from any cwd.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]

def family(m, j):
    n = 2*m+1
    negative = set(range(1, j)) | {m+2}
    positive = {m} | set(range(n-j+2, n+1))
    return sorted(i+n*(int(i in positive)-int(i in negative)) for i in range(1, n+1))

def vec(xs):
    return '![' + ', '.join(map(str, xs)) + ']'

def main():
    lines = ['import Guralnick.Affine', '', '/- Generated by scripts/generate_windows.py.',
             'Every proof uses kernel reduction via decide. These are NOT KL certificates. -/',
             'namespace Guralnick.Certificates', 'set_option maxRecDepth 100000',
             'set_option maxHeartbeats 2000000', '']
    records = []
    for m in range(2, 6):
        n = 2*m+1
        for j in range(1, m+1):
            w = family(m,j)
            residues = [(x-1)%n for x in w]
            inverse = [residues.index(i) for i in range(n)]
            winding = [(x-1)//n for x in w]
            name=f'm{m}j{j}'
            degree=2*j*(n-j)-2*(m-j)-3
            matrix=[[1,m-j,j-1],[0,1,0],[j-1,m-j,1]]
            c=m-j
            # p=next prime >=5(N-1), primality is checked in Lean too.
            p=5*(n-1)
            while any(p%d==0 for d in range(2,int(p**0.5)+1)): p+=1
            weight=[p]*(j-1)+[p-c-2]+[1]*c+[0]+[-1]*c+[c+2-p]+[-p]*(j-1)
            lines += [f'def {name}Certificate : WindowCertificate {n} where',
                      f'  residue := {vec(residues)}', f'  inverse := {vec(inverse)}',
                      f'  winding := {vec(winding)}',
                      f'theorem {name}_accepted : {name}Certificate.check = true := by decide',
                      f'def {name} : AffinePermutation {n} :=',
                      f'  {name}Certificate.toAffine {name}_accepted',
                      f'theorem {name}_window : {name}.window = {w} := by decide',
                      f'theorem {name}_family : {name}.window = familyWindow {m} {j} := by',
                      '  unfold familyWindow', '  rw [List.mergeSort_eq_insertionSort]', '  decide',
                      f'theorem {name}_increasing : {name}.window.Pairwise (· < ·) := by decide',
                      f'theorem {name}_matrix : matrixWindow {m} {name} = prescribedMatrix {m} {j} := by decide',
                      f'theorem {name}_inversionCount : {name}.inversionCount = {degree} := by decide',
                      f'theorem {name}_prime : Nat.Prime {p} := by decide',
                      f'theorem {name}_characteristic_bound : 5*({n}-1) ≤ {p} := by decide',
                      f'theorem {name}_dotZero :',
                      f'    List.ofFn ({name}.inverse.dotZero {p} (fun i => ({m} : ℤ) - i.val)) =',
                      f'      {weight} := by decide',
                      f'theorem {name}_restricted : DominantRestricted {p}',
                      f'    ({name}.inverse.dotZero {p} (fun i => ({m} : ℤ) - i.val)) := by decide',
                      f'theorem {name}_regular : Regular {p} (fun i : Fin {n} => ({m} : ℤ) - i.val)',
                      f'    ({name}.inverse.dotZero {p} (fun i => ({m} : ℤ) - i.val)) := by decide', '']
            records.append(dict(m=m,j=j,window=w,residues_zero_based=residues,inverse_zero_based=inverse,
                                winding=winding,inversion_count=degree,matrix=matrix,p=p,dot_zero=weight))
    lines += ['-- Invalid input is rejected: a residue map with a repeated image.',
              'def invalid : WindowCertificate 2 where',
              '  residue := ![0,0]', '  inverse := ![0,1]', '  winding := ![0,0]',
              'theorem invalid_rejected : invalid.check = false := by decide',
              '', 'end Guralnick.Certificates', '']
    (ROOT/'Guralnick/WindowExamples.lean').write_text('\n'.join(lines))
    (ROOT/'certificates/windows.json').write_text(json.dumps(records,indent=2)+'\n')
    print(f'Generated {len(records)} window certificates and one rejection test.')

if __name__ == '__main__': main()
